import html2canvas from "html2canvas-pro";
import jsPDF from "jspdf";
import autoTable from "jspdf-autotable";

type JsPDFWithAutoTable = jsPDF & {
  lastAutoTable?: {
    finalY?: number;
  };
};

export interface PDFOptions {
  filename: string;
  title: string;
  name: string;
  generatedAt: Date;
}

export async function generatePDFFromElement(
  elementId: string,
  opts: PDFOptions,
): Promise<string> {
  const element = document.getElementById(elementId);
  if (!element) {
    throw new Error(`Element with id "${elementId}" not found`);
  }

  const tempContainer = document.createElement("div");
  tempContainer.style.position = "absolute";
  tempContainer.style.left = "-9999px";
  tempContainer.style.top = "0";
  tempContainer.style.width = "210mm"; // A4 width
  tempContainer.style.backgroundColor = "#ffffff";
  tempContainer.style.fontFamily = "Arial, sans-serif";
  tempContainer.style.fontSize = "12px";
  tempContainer.style.lineHeight = "1.4";
  tempContainer.style.color = "#1f2937";
  tempContainer.style.padding = "12px";
  tempContainer.style.boxSizing = "border-box";

  const clonedElement = element.cloneNode(true) as HTMLElement;

  applyPDFStyles(clonedElement);

  processTablesForPDF(clonedElement);

  const tables = Array.from(clonedElement.querySelectorAll("table"));
  const tableDataList: Array<{
    data: ReturnType<typeof extractTableData>;
    element: HTMLElement;
  }> = [];

  tables.forEach((table) => {
    const tableData = extractTableData(table as HTMLElement);
    if (tableData) {
      tableDataList.push({ data: tableData, element: table as HTMLElement });
      table.remove();
    }
  });

  if (tableDataList.length === 0) {
    tempContainer.appendChild(clonedElement);
    document.body.appendChild(tempContainer);
  }

  const pdf = new jsPDF("p", "mm", "a4");

  const pageWidth = 210; // A4 width in mm
  const pageHeight = 297; // A4 height in mm
  const margin = 15;
  const headerHeight = 28;
  const footerHeight = 15;
  const contentWidth = pageWidth - margin * 2;
  const contentHeight = pageHeight - headerHeight - footerHeight - margin * 2;

  let imgData: string | null = null;
  let imgWidth = 0;
  let imgHeight = 0;

  try {
    if (tableDataList.length === 0) {
      const hasContent =
        clonedElement.textContent?.trim() || clonedElement.children.length > 0;

      if (hasContent) {
        const canvas = await html2canvas(tempContainer, {
          scale: 2,
          useCORS: true,
          allowTaint: true,
          backgroundColor: "#ffffff",
          logging: false,
          foreignObjectRendering: false,
          width: tempContainer.offsetWidth,
          height: tempContainer.offsetHeight,
        });

        imgData = canvas.toDataURL("image/png");
        imgWidth = contentWidth;
        imgHeight = (canvas.height * imgWidth) / canvas.width;
      }
    }

    pdf.setProperties({
      title: opts.title,
      subject: `Report generated by ${opts.name}`,
      creator: opts.name,
      author: opts.name,
    });

    let logoEl: HTMLImageElement | null = null;
    let computedLogoWidth = 0;
    const desiredLogoHeight = 12;
    try {
      logoEl = await new Promise<HTMLImageElement>((resolve) => {
        const img = new Image();
        img.crossOrigin = "anonymous";
        img.onload = () => resolve(img);
        img.onerror = () => resolve(img);
        img.src = "/logo.jpg";
      });
    } catch {
      logoEl = null;
    }

    if (logoEl && logoEl.width && logoEl.height) {
      computedLogoWidth = (logoEl.width / logoEl.height) * desiredLogoHeight;
    }

    if (tableDataList.length > 0) {
      let tableY = headerHeight + margin + 10;

      for (
        let tableIndex = 0;
        tableIndex < tableDataList.length;
        tableIndex++
      ) {
        const { data } = tableDataList[tableIndex];
        if (data) {
          autoTable(pdf, {
            startY: tableY,
            head: [data.headers],
            body: data.rows,
            styles: {
              fontSize: 8,
              cellPadding: 2,
              lineWidth: 0.2,
              overflow: "linebreak",
            },
            headStyles: {
              fillColor: [248, 250, 252],
              textColor: [55, 65, 81],
              lineWidth: 0.2,
            },
            alternateRowStyles: { fillColor: [250, 250, 250] },
            margin: { left: margin, right: margin },
            tableWidth: "auto",
            didDrawPage: () => {},
          });

          const last = (pdf as JsPDFWithAutoTable).lastAutoTable;
          tableY = (last?.finalY || tableY) + 6;

          if (tableIndex < tableDataList.length - 1) {
            const remainingHeight = pageHeight - tableY - footerHeight - margin;
            if (remainingHeight < 50) {
              pdf.addPage();
              tableY = headerHeight + margin + 10;
            }
          }
        }
      }
    } else if (imgData) {
      const availableHeight = contentHeight;
      let position = headerHeight + margin;
      let heightLeft = imgHeight - availableHeight;
      let yOffset = 0;

      pdf.addImage(imgData, "PNG", margin, position, imgWidth, imgHeight);

      while (heightLeft > 0) {
        pdf.addPage();
        yOffset = -(imgHeight - heightLeft - availableHeight);
        position = headerHeight + margin + yOffset;
        pdf.addImage(imgData, "PNG", margin, position, imgWidth, imgHeight);
        heightLeft -= availableHeight;
      }
    }

    const totalPages = pdf.getNumberOfPages();
    for (let i = 1; i <= totalPages; i++) {
      pdf.setPage(i);

      pdf.setFillColor(37, 99, 235);
      pdf.rect(0, 0, pageWidth, headerHeight, "F");

      pdf.setDrawColor(37, 99, 235);
      pdf.setLineWidth(0.5);
      pdf.line(0, headerHeight, pageWidth, headerHeight);

      pdf.setTextColor(255, 255, 255);
      const logoY = 5;
      const nameY = logoY + desiredLogoHeight / 2 + 2;

      if (logoEl && logoEl.complete && computedLogoWidth > 0) {
        try {
          pdf.addImage(
            logoEl,
            "JPEG",
            margin,
            logoY,
            computedLogoWidth,
            desiredLogoHeight,
          );
        } catch {}
        pdf.setFontSize(14);
        pdf.setFont("helvetica", "bold");
        pdf.text(opts.name, margin + computedLogoWidth + 8, nameY);
      } else {
        pdf.setFontSize(14);
        pdf.setFont("helvetica", "bold");
        pdf.text(opts.name, margin, nameY);
      }

      const titleY = logoY + desiredLogoHeight + 3;
      pdf.setFontSize(11);
      pdf.setFont("helvetica", "normal");
      pdf.text(opts.title, margin, titleY);

      pdf.setFontSize(9);
      pdf.setTextColor(191, 219, 254);
      const dateStr = new Intl.DateTimeFormat("en-US", {
        year: "numeric",
        month: "short",
        day: "2-digit",
        hour: "2-digit",
        minute: "2-digit",
      }).format(opts.generatedAt);
      pdf.text(`Generated: ${dateStr}`, pageWidth - margin, nameY, {
        align: "right",
      });

      pdf.setFillColor(248, 250, 252);
      pdf.rect(0, pageHeight - footerHeight, pageWidth, footerHeight, "F");

      pdf.setDrawColor(226, 232, 240);
      pdf.setLineWidth(0.5);
      pdf.line(
        0,
        pageHeight - footerHeight,
        pageWidth,
        pageHeight - footerHeight,
      );

      pdf.setFontSize(9);
      pdf.setTextColor(100, 116, 139);
      pdf.text(
        `Page ${i} of ${totalPages}`,
        pageWidth - margin,
        pageHeight - 5,
        {
          align: "right",
        },
      );

      pdf.text("Confidential Document", margin, pageHeight - 5);
    }

    const pdfBlob = pdf.output("blob");
    const pdfUrl = URL.createObjectURL(pdfBlob);

    return pdfUrl;
  } finally {
    if (tempContainer.parentNode === document.body) {
      document.body.removeChild(tempContainer);
    }
  }
}

function extractTableData(
  table: HTMLElement,
): { headers: string[]; rows: string[][] } | null {
  const htmlTable = table as HTMLTableElement;
  const thead = htmlTable.querySelector("thead");
  const tbody = htmlTable.querySelector("tbody");

  if (!thead || !tbody) return null;

  const headerCells = Array.from(thead.querySelectorAll("th, td"));
  const headers = headerCells.map((cell) => {
    return cell.textContent?.trim() || "";
  });

  const bodyRows = Array.from(tbody.querySelectorAll("tr"));
  const rows = bodyRows.map((row) => {
    const cells = Array.from(row.querySelectorAll("td, th"));
    return cells.map((cell) => {
      return cell.textContent?.trim() || "";
    });
  });

  if (headers.length === 0 || rows.length === 0) return null;

  return { headers, rows };
}

function processTablesForPDF(element: HTMLElement): void {
  const tables = element.querySelectorAll("table");

  tables.forEach((table) => {
    const htmlTable = table as HTMLTableElement;
    const thead = htmlTable.querySelector("thead");
    const tbody = htmlTable.querySelector("tbody");

    if (!thead || !tbody) return;

    const rows = Array.from(tbody.querySelectorAll("tr"));
    if (rows.length === 0) return;

    const estimatedRowHeight = 30;
    const pageHeightPx = 1100;
    const headerHeightPx = 150;
    const footerHeightPx = 50;
    const availableHeight = pageHeightPx - headerHeightPx - footerHeightPx;
    const maxRowsPerPage = Math.floor(availableHeight / estimatedRowHeight) - 1;

    if (rows.length <= maxRowsPerPage) {
      return;
    }

    const pages: HTMLTableRowElement[][] = [];
    for (let i = 0; i < rows.length; i += maxRowsPerPage) {
      pages.push(rows.slice(i, i + maxRowsPerPage) as HTMLTableRowElement[]);
    }

    htmlTable.setAttribute("data-pdf-split-table", "true");
    htmlTable.setAttribute("data-pdf-max-rows", maxRowsPerPage.toString());
  });
}

function applyPDFStyles(element: HTMLElement): void {
  const allElements = element.querySelectorAll("*");

  allElements.forEach((el) => {
    const htmlEl = el as HTMLElement;

    htmlEl.style.fontFamily = "Arial, sans-serif";
    htmlEl.style.color = "#1f2937";
    htmlEl.style.lineHeight = "1.4";

    if (el.tagName === "TABLE") {
      htmlEl.style.width = "100%";
      htmlEl.style.borderCollapse = "separate";
      htmlEl.style.borderSpacing = "0";
      htmlEl.style.marginBottom = "8px";
      htmlEl.style.marginTop = "6px";
      htmlEl.style.fontSize = "8px";
      htmlEl.style.pageBreakInside = "auto";
      htmlEl.style.breakInside = "auto";
      htmlEl.style.tableLayout = "fixed";
    }

    if (el.tagName === "THEAD") {
      htmlEl.style.display = "table-header-group";
      htmlEl.style.pageBreakInside = "avoid";
      htmlEl.style.breakInside = "avoid";
      htmlEl.style.position = "sticky";
      htmlEl.style.top = "0";
      htmlEl.style.zIndex = "10";
      htmlEl.style.backgroundColor = "#f8fafc";
    }

    if (el.tagName === "TBODY") {
      htmlEl.style.display = "table-row-group";
    }

    if (el.tagName === "TABLE") {
      const prevSibling = el.previousElementSibling as HTMLElement;
      if (prevSibling && prevSibling.tagName !== "TABLE") {
        htmlEl.style.pageBreakBefore = "auto";
        htmlEl.style.breakBefore = "auto";
      }
    }

    if (el.tagName === "TR") {
      htmlEl.style.pageBreakInside = "avoid";
      htmlEl.style.breakInside = "avoid";
      htmlEl.style.pageBreakAfter = "auto";
      htmlEl.style.breakAfter = "auto";
      htmlEl.style.display = "table-row";
      htmlEl.style.minHeight = "22px";
      htmlEl.style.height = "auto";
    }

    if (el.tagName === "TH") {
      htmlEl.style.backgroundColor = "#f8fafc";
      htmlEl.style.border = "1px solid #e2e8f0";
      htmlEl.style.borderTop = "1px solid #e2e8f0";
      htmlEl.style.borderBottom = "1px solid #e2e8f0";
      htmlEl.style.padding = "3px 4px";
      htmlEl.style.fontWeight = "bold";
      htmlEl.style.fontSize = "8px";
      htmlEl.style.color = "#374151";
      htmlEl.style.pageBreakInside = "avoid";
      htmlEl.style.breakInside = "avoid";
      htmlEl.style.lineHeight = "1.2";
      htmlEl.style.whiteSpace = "nowrap";
    }

    if (el.tagName === "TD") {
      htmlEl.style.border = "1px solid #e2e8f0";
      htmlEl.style.borderTop = "1px solid #e2e8f0";
      htmlEl.style.borderBottom = "1px solid #e2e8f0";
      htmlEl.style.padding = "2px 4px";
      htmlEl.style.fontSize = "8px";
      htmlEl.style.pageBreakInside = "avoid";
      htmlEl.style.breakInside = "avoid";
      htmlEl.style.lineHeight = "1.2";
      htmlEl.style.wordWrap = "break-word";
    }

    if (
      el.classList.contains("rounded-md") ||
      el.classList.contains("border")
    ) {
      htmlEl.style.border = "1px solid #e2e8f0";
      htmlEl.style.borderRadius = "4px";
      htmlEl.style.padding = "12px";
      htmlEl.style.marginBottom = "12px";
      htmlEl.style.backgroundColor = "#ffffff";
    }

    if (el.tagName === "H1" || el.tagName === "H2" || el.tagName === "H3") {
      htmlEl.style.color = "#111827";
      htmlEl.style.fontWeight = "bold";
      htmlEl.style.marginBottom = "12px";
      htmlEl.style.marginTop = "16px";
    }

    if (el.tagName === "H1") {
      htmlEl.style.fontSize = "18px";
    } else if (el.tagName === "H2") {
      htmlEl.style.fontSize = "16px";
    } else if (el.tagName === "H3") {
      htmlEl.style.fontSize = "14px";
    }

    if (el.tagName === "UL" || el.tagName === "OL") {
      htmlEl.style.marginLeft = "20px";
      htmlEl.style.marginBottom = "12px";
    }

    if (el.tagName === "LI") {
      htmlEl.style.marginBottom = "4px";
      htmlEl.style.fontSize = "11px";
    }

    if (el.tagName === "P") {
      htmlEl.style.marginBottom = "8px";
      htmlEl.style.fontSize = "11px";
    }

    if (el.classList.contains("text-muted-foreground")) {
      htmlEl.style.color = "#6b7280";
      htmlEl.style.fontSize = "10px";
    }

    if (
      el.classList.contains("font-semibold") ||
      el.classList.contains("font-bold")
    ) {
      htmlEl.style.fontWeight = "bold";
    }

    if (el.classList.contains("text-xl")) {
      htmlEl.style.fontSize = "16px";
    }

    if (el.classList.contains("text-sm")) {
      htmlEl.style.fontSize = "10px";
    }

    if (el.classList.contains("grid")) {
      htmlEl.style.display = "block";
      htmlEl.style.marginBottom = "16px";
    }

    if (el.classList.contains("px-2") && el.classList.contains("py-1")) {
      htmlEl.style.padding = "4px 8px";
      htmlEl.style.borderRadius = "4px";
      htmlEl.style.fontSize = "9px";
      htmlEl.style.fontWeight = "bold";
    }

    htmlEl.style.transition = "none";
    htmlEl.style.transform = "none";

    if (el.classList.contains("space-y-4")) {
      htmlEl.style.marginBottom = "16px";
    }

    if (el.classList.contains("space-y-2")) {
      htmlEl.style.marginBottom = "8px";
    }
  });
}

export function openPDFInNewTab(pdfUrl: string): void {
  const newWindow = window.open(pdfUrl, "_blank");
  if (!newWindow) {
    throw new Error(
      "Failed to open PDF in new tab. Please check your popup blocker settings.",
    );
  }

  setTimeout(() => {
    URL.revokeObjectURL(pdfUrl);
  }, 10000);
}
